#!/usr/bin/env python3
"""Mechanically extracts C++ static data-table arrays into C# source.

This is a seed of the full libclang-based CppModelExtractor described in the
migration plan. For the POC it handles exactly one table (normal_table from
src/data_tables.cpp) via a targeted regex rather than a full AST walk, so the
pipeline can be validated end-to-end before investing in the general libclang
tool. It deliberately does NOT hand-retype any numeric literals -- values are
parsed out of the original C++ source and re-emitted verbatim, which is the
whole point: a transcription tool can't introduce a flipped-digit bug the way
manually retyping (by a human or an LLM) could.

Usage: python extract_data_tables.py <path-to-data_tables.cpp> <output-dir>
"""
import re
import sys
from pathlib import Path

HEADER = """// <auto-generated by tools/CppModelExtractor/extract_data_tables.py>
// Source: src/data_tables.cpp -- do not hand-edit, regenerate instead.

namespace Umoria.Core.Data.Generated;

public static class DataTables
{
"""

FOOTER = """}
"""


def extract_normal_table(source: str) -> str:
    match = re.search(
        r"uint16_t\s+normal_table\[NORMAL_TABLE_SIZE\]\s*=\s*\{(.*?)\};",
        source,
        re.DOTALL,
    )
    if not match:
        raise SystemExit("normal_table array literal not found")

    values = [v.strip() for v in match.group(1).split(",") if v.strip()]
    if len(values) != 256:
        raise SystemExit(f"expected 256 values, found {len(values)}")

    for v in values:
        if not v.isdigit():
            raise SystemExit(f"unexpected non-numeric literal: {v!r}")

    lines = []
    for i in range(0, len(values), 8):
        row = ", ".join(f"{int(v)}" for v in values[i : i + 8])
        lines.append(f"        {row},")

    body = "\n".join(lines)
    return (
        "    // Pseudo-normal distribution lookup table (SD=64). See\n"
        "    // randomNumberNormalDistribution() in RandomNumber.cs.\n"
        "    public static readonly ushort[] NormalTable =\n    {\n"
        + body
        + "\n    };\n"
    )


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit(f"usage: {sys.argv[0]} <data_tables.cpp> <output-dir>")

    src_path = Path(sys.argv[1])
    out_dir = Path(sys.argv[2])
    out_dir.mkdir(parents=True, exist_ok=True)

    source = src_path.read_text(encoding="utf-8")
    body = extract_normal_table(source)

    out_path = out_dir / "DataTables.cs"
    out_path.write_text(HEADER + body + FOOTER, encoding="utf-8")
    print(f"wrote {out_path} ({out_path.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
